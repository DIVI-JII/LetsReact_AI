// Writes server/src/data/curriculum.ts from the lesson data in src/data/lessons.
// The tutor uses it to know what each module covers. Re-run after adding or editing lessons:
//   npm run curriculum        (from the project root)
import { writeFileSync } from 'node:fs';
import { lessons } from '../src/data/lessons/index';

const out = lessons
  .filter((l) => l.content)
  .map((l) => ({
    id: l.id,
    weekNumber: l.weekNumber,
    number: l.number,
    title: l.title,
    summary: l.summary,
    lead: l.content!.explanation.lead,
    analogy: `${l.content!.explanation.analogy.title}: ${l.content!.explanation.analogy.body}`,
    points: l.content!.explanation.points,
    practice: l.content!.practice.prompt,
    quiz: l.content!.quiz.questions.map((q) => ({
      question: q.prompt,
      answer: q.options.find((o) => o.id === q.correctOptionId)?.text ?? '',
      why: q.explanation,
    })),
  }));

const header = `// GENERATED by scripts/genCurriculum.ts from src/data/lessons. Do not edit by hand.
export interface CurriculumLesson {
  id: string;
  weekNumber: number;
  number: number;
  title: string;
  summary: string;
  lead: string;
  analogy: string;
  points: string[];
  practice: string;
  quiz: { question: string; answer: string; why: string }[];
}

export const curriculum: CurriculumLesson[] = `;
const target = new URL('../server/src/data/curriculum.ts', import.meta.url);
writeFileSync(target, header + JSON.stringify(out, null, 2) + ';\n');
console.log(`Wrote ${out.length} lessons to server/src/data/curriculum.ts`);
